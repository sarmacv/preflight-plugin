import type { Severity } from '../skills/types';
import type { PrKind } from './branchName';

export interface AddressedCheck {
  id: string;
  name: string;
  severity: Severity;
  /** Reviewer guidance specific to this check. */
  verify?: string;
}

export interface PrText {
  title: string;
  body: string;
  commitHeadline: string;
  commitBody: string;
}

export const PR_LABEL = { name: 'preflight', color: 'F58025', description: 'Opened by Preflight' };

const SEV_ORDER: Severity[] = ['critical', 'high', 'medium', 'low'];

export function buildPrText(kind: PrKind, checks: AddressedCheck[], files: string[], notes: string[], targetBranch: string): PrText {
  const sorted = [...checks].sort((a, b) => SEV_ORDER.indexOf(a.severity) - SEV_ORDER.indexOf(b.severity));
  const title =
    kind === 'coverage'
      ? `Preflight: add tests for ${files.length} low-coverage file${files.length === 1 ? '' : 's'}`
      : sorted.length === 1
        ? `Preflight: ${sorted[0].name}`
        : `Preflight: fix ${sorted.length} repository checks`;

  const lines: string[] = [];
  if (kind === 'coverage') {
    lines.push(
      'This draft PR adds tests written by an AI model for the files with the lowest coverage reported by SonarQube.',
      '',
      '> [!WARNING]',
      '> Preflight works through the GitHub API without cloning the repository, so **these tests have not been run**. Rely on this repository\'s CI to validate them, and fix or drop any test that fails before marking the PR ready for review.',
      '',
    );
  } else {
    lines.push(`This PR fixes repository checks that failed a Preflight scan of \`${targetBranch}\`.`, '');
  }

  lines.push('### Checks addressed', '', '| Check | ID | Severity |', '| --- | --- | --- |');
  for (const c of sorted) lines.push(`| ${c.name} | \`${c.id}\` | ${c.severity} |`);
  lines.push('', '### Files', '');
  for (const f of files) lines.push(`- \`${f}\``);

  const verify = [...sorted.filter((c) => c.verify).map((c) => `**${c.name}:** ${c.verify}`), ...notes.filter(Boolean)];
  lines.push('', '### What to verify', '');
  if (kind === 'coverage') lines.push('- CI runs the new tests and they pass.', '- The tests assert real behaviour rather than restating the implementation.');
  for (const v of verify) lines.push(v.startsWith('- ') ? v : `- ${v}`);
  if (verify.length === 0 && kind === 'fixes') lines.push('- The generated files are accurate for this repository.');
  lines.push('', '---', '_Generated by Preflight. Check. Fix. Ship._');

  const commitHeadline = kind === 'coverage' ? `test: add tests for low-coverage files (Preflight)` : `chore: fix ${sorted.length} Preflight check${sorted.length === 1 ? '' : 's'}`;
  const commitBody = sorted.map((c) => `- ${c.id} (${c.severity})`).join('\n') + '\n\nGenerated by Preflight.';
  return { title, body: lines.join('\n'), commitHeadline, commitBody };
}
