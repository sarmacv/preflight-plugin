// Deterministic fix generators referenced by skills as `fix: { kind: builtin, name: ... }`.
import type { RepoContext } from '../engine/context';
import type { FixProposal } from '../ai/provider';
import { exportSbom, readManifests, type Dependency } from '../skills/rules/dependencies';
import { CI_ACTION_GLOBS } from '../skills/rules/ciGlobs';

export interface BuiltinFix extends FixProposal {
  /** Paths whose content the user is expected to review and edit before the PR is built. */
  editable?: string[];
}

export type BuiltinFixFn = (ctx: RepoContext) => Promise<BuiltinFix>;

const DAY = 86_400_000;
const BOT = /\[bot\]$|^dependabot|^github-actions|^renovate/i;

async function codeownersFromHistory(ctx: RepoContext): Promise<BuiltinFix> {
  const { owner, repo, ref } = ctx.info;
  const since = new Date(Date.now() - 180 * DAY).toISOString();
  const counts = new Map<string, number>();
  let page = 1;
  for (; page <= 3; page++) {
    const { data } = await ctx.gh.rest.repos.listCommits({ owner, repo, sha: ref, since, per_page: 100, page, request: { signal: ctx.signal } });
    for (const c of data) {
      const login = c.author?.login;
      if (login && !BOT.test(login)) counts.set(login, (counts.get(login) ?? 0) + 1);
    }
    if (data.length < 100) break;
  }

  const ranked = [...counts].sort((a, b) => b[1] - a[1]).map(([login]) => login);
  const owners: string[] = [];
  for (const login of ranked) {
    if (owners.length === 3) break;
    try {
      const { data } = await ctx.gh.rest.repos.getCollaboratorPermissionLevel({ owner, repo, username: login, request: { signal: ctx.signal } });
      if (['admin', 'maintain', 'write'].includes(data.role_name ?? data.permission)) owners.push(login);
    } catch {
      // Reading permissions needs push access; keep the candidate and let the user confirm.
      owners.push(login);
    }
  }

  const header = [
    '# CODEOWNERS: reviewers GitHub requests automatically for matching paths.',
    '# Generated by Preflight from the most active committers in the last 180 days.',
    '# Confirm these owners (or replace them with a team such as @org/team) before merging.',
    '',
  ];
  const rule = owners.length ? `* ${owners.map((o) => `@${o}`).join(' ')}` : `# TODO: no recent committers found. Add an owner, e.g.\n# * @${owner}/team`;
  return {
    changes: [{ path: '.github/CODEOWNERS', content: [...header, rule, ''].join('\n') }],
    notes: owners.length
      ? `Owners were proposed from commit history: ${owners.map((o) => `@${o}`).join(', ')}. Confirm each has write access and is the right reviewer.`
      : 'No recent committers were found; add an owner before merging.',
    editable: ['.github/CODEOWNERS'],
  };
}

