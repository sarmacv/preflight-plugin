async function gitignoreLicense(ctx: RepoContext): Promise<BuiltinFix> {
  const changes = [];
  const notes: string[] = [];
  if (!ctx.exists('.gitignore')) {
    const sections = IGNORES.filter(([, globs]) => ctx.match(globs).length > 0).map(([name, , body]) => `# ${name}\n${body}`);
    sections.push('# Editors and OS\n.idea/\n.vscode/*\n!.vscode/extensions.json\n*.swp\n.DS_Store\nThumbs.db');
    changes.push({ path: '.gitignore', content: `# Generated by Preflight\n\n${sections.join('\n\n')}\n` });
    notes.push('Check that .gitignore doesn\'t exclude files this repository intentionally commits.');
  }
  const hasLicense = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'COPYING', 'LICENCE', 'LICENCE.md'].some((f) => ctx.exists(f));
  if (!hasLicense) {
    if (ctx.info.private === false) {
      notes.push('This repository is public, so Preflight did not choose a licence. Pick one with your legal team.');
    } else {
      const year = new Date().getFullYear();
      changes.push({
        path: 'LICENSE',
        content: `Copyright (c) ${year} ${ctx.info.owner}. All rights reserved.\n\nThis software is proprietary and confidential. It is provided for internal use by ${ctx.info.owner} only.\nNo part of it may be copied, distributed or used outside ${ctx.info.owner} without written permission.\n`,
      });
      notes.push(`LICENSE uses a proprietary notice for "${ctx.info.owner}". Replace it with your organisation's standard text if it differs.`);
    }
  }
  return { changes, notes: notes.map((n) => `- ${n}`).join('\n') };
}

function spdxFromDependencies(ctx: RepoContext, deps: Dependency[]): string {
  const purlType: Record<string, string> = { npm: 'npm', pypi: 'pypi', maven: 'maven', golang: 'golang', cargo: 'cargo', nuget: 'nuget', gem: 'gem', composer: 'composer', 'github-actions': 'githubactions' };
  const id = (i: number) => `SPDXRef-Package-${i}`;
  const packages = deps.map((d, i) => {
    const name = d.ecosystem === 'maven' ? d.name.replace(':', '/') : d.name;
    return {
      SPDXID: id(i),
      name: d.name,
      versionInfo: d.version ?? 'NOASSERTION',
      downloadLocation: 'NOASSERTION',
      filesAnalyzed: false,
      licenseConcluded: d.license ?? 'NOASSERTION',
      externalRefs: d.version
        ? [{ referenceCategory: 'PACKAGE-MANAGER', referenceType: 'purl', referenceLocator: `pkg:${purlType[d.ecosystem]}/${encodeURIComponent(name).replace(/%2F/g, '/')}@${encodeURIComponent(d.version)}` }]
        : [],
    };
  });
  const doc = {
    spdxVersion: 'SPDX-2.3',
    dataLicense: 'CC0-1.0',
    SPDXID: 'SPDXRef-DOCUMENT',
    name: `${ctx.fullName}@${ctx.info.ref}`,
    documentNamespace: `https://github.com/${ctx.fullName}/sbom/${ctx.info.sha}`,
    creationInfo: { created: new Date().toISOString(), creators: ['Tool: Preflight'] },
    packages,
    relationships: packages.map((p) => ({ spdxElementId: 'SPDXRef-DOCUMENT', relationshipType: 'DESCRIBES', relatedSpdxElement: p.SPDXID })),
  };
  return `${JSON.stringify(doc, null, 2)}\n`;
}

async function generateSbom(ctx: RepoContext): Promise<BuiltinFix> {
  if (ctx.isDefaultBranch) {
    const exported = await exportSbom(ctx);
    if (exported?.sbom.packages?.length) {
      return {
        changes: [{ path: 'sbom/sbom.spdx.json', content: `${JSON.stringify(exported.sbom, null, 2)}\n` }],
        notes: '- The SBOM is GitHub\'s dependency graph export. Add a CI step (for example anchore/sbom-action) to keep it current on each release.',
      };
    }
  }
  const deps = await readManifests(ctx);
  if (deps.length === 0) throw new Error('No manifests or lockfiles to build an SBOM from');
  return {
    changes: [{ path: 'sbom/sbom.spdx.json', content: spdxFromDependencies(ctx, deps) }],
    notes: `- The SBOM was generated from ${deps.length} dependencies declared in manifests and lockfiles on \`${ctx.info.ref}\`. Versions from ranges without a lockfile are approximate.\n- Add a CI step (for example anchore/sbom-action) to keep it current on each release.`,
  };
}

const USES_LINE = /^(\s*-?\s*uses:\s*["']?)([\w.-]+\/[\w.-]+(?:\/[^@\s"']*)?)@([^\s"'#]+)(["']?)(.*)$/;

async function pinActions(ctx: RepoContext): Promise<BuiltinFix> {
  const shaCache = new Map<string, Promise<string | undefined>>();
  const resolve = (action: string, ref: string) => {
    const [o, r] = action.split('/');
    const key = `${o}/${r}@${ref}`;
    let p = shaCache.get(key);
    if (!p) {
      p = ctx.gh.rest.repos
        .getCommit({ owner: o, repo: r, ref, request: { signal: ctx.signal } })
        .then((res) => res.data.sha)
        .catch(() => undefined);
      shaCache.set(key, p);
    }
    return p;
  };

  const changes = [];
  const unresolved: string[] = [];
  for (const file of ctx.match(CI_ACTION_GLOBS)) {
    const text = await ctx.read(file);
    if (!text) continue;
    let changed = false;
    const lines = await Promise.all(
      text.split('\n').map(async (line) => {
        const m = USES_LINE.exec(line);
        if (!m || /^[0-9a-f]{40}$/.test(m[3])) return line;
        const sha = await resolve(m[2], m[3]);
        if (!sha) {
          unresolved.push(`${file}: ${m[2]}@${m[3]}`);
          return line;
        }
        changed = true;
        const trailing = m[5].replace(/^\s*#.*$/, '');
        return `${m[1]}${m[2]}@${sha}${m[4]}${trailing} # ${m[3]}`;
      }),
    );
    if (changed) changes.push({ path: file, content: lines.join('\n') });
  }

  const notes = ['- Each action is pinned to the commit its tag pointed to today; the original tag is kept as a comment. Dependabot can keep SHA pins up to date.'];
  if (unresolved.length) notes.push(`- Could not resolve: ${unresolved.join(', ')}`);
  notes.push('- Missing lockfiles and floating Docker tags need a local build and are not changed here.');
  return { changes, notes: notes.join('\n') };
}

