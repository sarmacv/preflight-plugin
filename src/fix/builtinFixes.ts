async function prIssueTemplates(ctx: RepoContext): Promise<BuiltinFix> {
  const changes = [];
  const hasPr = ctx.match(['pull_request_template.md', '.github/pull_request_template.md', 'docs/pull_request_template.md', '.github/PULL_REQUEST_TEMPLATE/*.md', 'PULL_REQUEST_TEMPLATE/*.md']).length > 0;
  const hasIssue = ctx.match(['issue_template.md', '.github/issue_template.md', '.github/ISSUE_TEMPLATE/*']).length > 0;
  if (!hasPr) changes.push({ path: '.github/pull_request_template.md', content: PR_TEMPLATE });
  if (!hasIssue) {
    changes.push({ path: '.github/ISSUE_TEMPLATE/bug_report.yml', content: BUG_FORM });
    changes.push({ path: '.github/ISSUE_TEMPLATE/feature_request.yml', content: FEATURE_FORM });
  }
  return { changes, notes: 'Adjust the template sections to match how this team works.' };
}

