import { describe, expect, it } from 'vitest';
import { checkOrCategory, renderBranchName, resolveCollision, validateBranchName } from '../src/fix/branchName';
import { buildPrText } from '../src/fix/prBody';
import { diffLines, hunks } from '../src/shared/diff';

const date = new Date(2026, 9, 28);

describe('renderBranchName', () => {
  it('fills every placeholder', () => {
    const name = renderBranchName('{user}/{repo}/{check-or-category}/{type}-{date}-{shortid}', {
      user: 'Jane Doe', repo: 'api', checkOrCategory: 'ai-readiness', type: 'fixes', date, shortid: 'abc123',
    });
    expect(name).toBe('Jane-Doe/api/ai-readiness/fixes-20261028-abc123');
  });

  it('uses the default template when empty', () => {
    expect(renderBranchName('  ', { user: 'u', repo: 'r', checkOrCategory: 'c', type: 'coverage', date, shortid: 'ffffff' })).toBe('preflight/coverage/20261028-ffffff');
  });

  it('leaves unknown placeholders for validation to catch', () => {
    const name = renderBranchName('x/{ticket}', { user: 'u', repo: 'r', checkOrCategory: 'c', type: 'fixes', date });
    expect(validateBranchName(name)).toMatch(/Unknown placeholder/);
  });

  it('slugs unsafe characters in values', () => {
    expect(renderBranchName('{repo}', { user: 'u', repo: 'my repo..v2:beta', checkOrCategory: 'c', type: 'fixes', date })).toBe('my-repo.v2-beta');
  });
});

describe('validateBranchName', () => {
  it.each([
    ['', /empty/],
    ['feature/a b', /characters/],
    ['a..b', /\.\./],
    ['/a', /empty path segment/],
    ['a//b', /empty path segment/],
    ['-a', /Starts with/],
    ['a/.hidden', /segment/],
    ['a.lock', /segment|\.lock/],
  ])('rejects %s', (name, re) => {
    expect(validateBranchName(name)).toMatch(re);
  });

  it('accepts normal names and applies the org pattern', () => {
    expect(validateBranchName('preflight/fixes/20261028-abc123')).toBeUndefined();
    expect(validateBranchName('preflight/fixes/x', '^(feature|chore)/')).toMatch(/pattern/);
    expect(validateBranchName('chore/preflight-x', '^(feature|chore)/')).toBeUndefined();
    expect(validateBranchName('chore/x', '([')).toMatch(/not a valid regular expression/);
  });
});

describe('resolveCollision', () => {
  it('appends a numeric suffix until free', async () => {
    const taken = new Set(['b', 'b-2']);
    expect(await resolveCollision('a', async (n) => taken.has(n))).toBe('a');
    expect(await resolveCollision('b', async (n) => taken.has(n))).toBe('b-3');
  });
});

describe('checkOrCategory', () => {
  it('names one check, a shared category, or multi', () => {
    expect(checkOrCategory([{ id: 'x', category: 'c' }])).toBe('x');
    expect(checkOrCategory([{ id: 'x', category: 'c' }, { id: 'y', category: 'c' }])).toBe('c');
    expect(checkOrCategory([{ id: 'x', category: 'c' }, { id: 'y', category: 'd' }])).toBe('multi');
  });
});

describe('buildPrText', () => {
  it('lists checks by severity with the Preflight footer', () => {
    const t = buildPrText('fixes', [{ id: 'low-one', name: 'Low', severity: 'low' }, { id: 'crit', name: 'Crit', severity: 'critical' }], ['a.md'], ['- Check a.md'], 'main');
    expect(t.title).toBe('Preflight: fix 2 repository checks');
    expect(t.body.indexOf('`crit`')).toBeLessThan(t.body.indexOf('`low-one`'));
    expect(t.body).toContain('| Crit | `crit` | critical |');
    expect(t.body).toContain('- Check a.md');
    expect(t.body).toContain('Generated by Preflight');
    expect(t.commitBody).toContain('- crit (critical)');
  });

  it('says coverage tests were not run', () => {
    const t = buildPrText('coverage', [{ id: 'test-coverage', name: 'Coverage', severity: 'high' }], ['a.test.ts', 'b.test.ts'], [], 'main');
    expect(t.title).toBe('Preflight: add tests for 2 low-coverage files');
    expect(t.body).toMatch(/these tests have not been run/);
  });
});

describe('diff', () => {
  it('produces a minimal line diff', () => {
    const ops = diffLines('a\nb\nc\n', 'a\nB\nc\nd\n');
    expect(ops.map((o) => `${o.kind[0]}${o.text}`)).toEqual(['sa', 'db', 'aB', 'sc', 'ad']);
  });

  it('handles empty sides', () => {
    expect(diffLines('', 'x\ny').map((o) => o.kind)).toEqual(['add', 'add']);
    expect(diffLines('x', '').map((o) => o.kind)).toEqual(['del']);
  });

  it('groups changes into hunks with context', () => {
    const before = Array.from({ length: 30 }, (_, i) => `l${i}`).join('\n');
    const after = before.replace('l2', 'L2').replace('l25', 'L25');
    const hs = hunks(diffLines(before, after), 2);
    expect(hs).toHaveLength(2);
    expect(hs[0].ops.map((o) => o.text)).toEqual(['l0', 'l1', 'l2', 'L2', 'l3', 'l4']);
  });
});
